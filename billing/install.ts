// Adds or refreshes pronto-billing in a pronto app (bin/pronto-billing):
//   install.ts <app-dir> [owner-hash]
// Regenerated every time, each marked as this host's: the program's schema,
// table, migration and services (billing_plugin.cue), the door's routes
// (pronto/billing.cue, billing/billing.nu), and the code the billing service
// and a local broker run (billing/). Written once, then the app's own: what it
// sells (billing_spec.cue), owned by the author's payout secret.
import { RULES } from "./rules.ts";
const here = new URL(".", import.meta.url).pathname;
const [appArg, owner] = Deno.args;
if (!appArg) throw new Error("usage: install.ts <app-dir> [owner-hash]");
const app = appArg.replace(/\/$/, "");
const program = await Deno.readTextFile(`${app}/program.cue`);
const pkg = /^package\s+([a-z][a-z0-9_]*)\s*$/m.exec(program)?.[1];
if (!pkg) throw new Error(`${app}/program.cue names no package`);

async function write(path: string, text: string, seed = false) {
  const to = `${app}/${path}`;
  const held = await Deno.readTextFile(to).catch(() => null);
  if (held !== null && (seed || held === text)) return;
  await Deno.mkdir(to.replace(/\/[^/]+$/, ""), { recursive: true });
  await Deno.writeTextFile(to, text);
  console.log(`pronto-billing: wrote ${path}`);
}
const template = async (name: string) => (await Deno.readTextFile(`${here}app/${name}`)).replaceAll("__PACKAGE__", pkg);

await write("billing_plugin.cue", await template("billing_plugin.cue"));
await write("pronto/billing.cue", await template("pronto_billing.cue"));
await write("billing/billing.nu", await template("billing.nu"));
// rules.cue itself, as the app's _billingRules: its billing_plugin.cue holds the spec to it, and its
// generate writes billing/rules.ts from it (billing.nu's rules), so the app holds the source.
const rules = (await Deno.readTextFile(`${here}rules.cue`)).replace(/^package billing$/m, `package ${pkg}`).replace(/^rules:/gm, "_billingRules:");
await write("billing_rules.cue", `// generated by pronto-billing from billing/rules.cue — do not edit\n${rules}`);
// The lists the app's own CUE reads (its analytics' trial states, its claim states), in the app's `spec` package, so
// there is one owner: rules.cue. The app imports `<its module>/spec` and uses spec.billingTrialStates and
// spec.billingClaimStates instead of writing the words again.
const list = (xs: readonly string[]) => `[${xs.map((x) => JSON.stringify(x)).join(", ")}]`;
await write("spec/billing_rules.cue", `// generated by pronto-billing from billing/rules.cue — do not edit
package spec

// Where a trial stands (billing.trial.state), as the broker words it.
billingTrialStates: ${list(RULES.trialStates)}

// Where a row of the broker's claim table stands.
billingClaimStates: ${list(RULES.claimStates)}
`);
// The broker's tables, as an add-only, idempotent raw migration in the app's database migrations: the broker runs
// no DDL itself and checks at start that they are there. Named to sort (LC_ALL=C) after the app's latest raw
// migration when first written, and rewritten in place under that name on every later install.
{
  const dir = "services/database/migrations";
  const names: string[] = [];
  try {
    for await (const e of Deno.readDir(`${app}/${dir}`)) if (e.isFile && e.name.endsWith(".sql")) names.push(e.name);
  } catch { /* no migrations yet: the first is the app's to number */ }
  const held = names.find((n) => n.endsWith("_billing_broker.sql"));
  let name = held;
  if (!name) {
    const latest = names.map((n) => /^(\d+)_/.exec(n)?.[1]).filter((n): n is string => !!n).sort().at(-1);
    name = `${String(latest ? Number(latest) + 10 : 10).padStart(Math.max(3, latest?.length ?? 3), "0")}_billing_broker.sql`;
  }
  await write(`${dir}/${name}`, await Deno.readTextFile(`${here}broker/schema.sql`));
}
for (const f of ["service.ts", "entitlement.ts", "shared.ts", "broker/core.ts", "broker/main.ts", "broker/stripe.ts", "broker/door.ts", "broker/fake.ts", "broker/store.ts", "broker/vendor/postgres.js"]) {
  await write(`billing/${f}`, await Deno.readTextFile(`${here}${f}`));
}
if (!owner && !(await Deno.stat(`${app}/billing_spec.cue`).catch(() => null))) {
  console.log("pronto-billing: no owner given; run `deno run billing/owner.ts new` and put its hash in billing_spec.cue");
}
await write("billing_spec.cue", (await template("billing_spec.cue")).replace("__OWNER__", owner ?? ""), true);
